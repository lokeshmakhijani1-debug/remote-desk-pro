-- Owner-scoped workflow persistence is accessed through authenticated FastAPI routes only.
-- The FastAPI backend connects as the verified postgres role (BYPASSRLS); browser and
-- agent clients do not access this table through Supabase PostgREST.
CREATE TABLE IF NOT EXISTS public.rdp_saved_workflows (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id INTEGER NOT NULL REFERENCES public.rdp_users(id) ON DELETE CASCADE,
 name VARCHAR(120) NOT NULL,
 description VARCHAR(1000) NOT NULL DEFAULT '',
 tags JSONB NOT NULL DEFAULT '[]'::jsonb,
 workflow JSONB NOT NULL,
 source_recording VARCHAR(255),
 community_workflow_id INTEGER,
 is_public BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT rdp_saved_workflows_size CHECK (pg_column_size(workflow) <= 2097152)
);
CREATE INDEX IF NOT EXISTS idx_rdp_saved_workflows_owner_updated ON public.rdp_saved_workflows (owner_id, updated_at DESC);

-- No anon/authenticated policies are intentionally defined. RLS blocks Data API
-- roles subject to RLS; the server-side postgres backend role bypasses RLS.
ALTER TABLE public.rdp_saved_workflows ENABLE ROW LEVEL SECURITY;
REVOKE TRUNCATE ON TABLE public.rdp_saved_workflows FROM anon, authenticated;
