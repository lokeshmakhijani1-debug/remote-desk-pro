-- Owner-scoped private workflow library; public copies are mirrored to rdp_community_workflows.
CREATE TABLE IF NOT EXISTS public.rdp_saved_workflows (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id INTEGER NOT NULL REFERENCES public.rdp_users(id) ON DELETE CASCADE,
 name VARCHAR(120) NOT NULL,
 description VARCHAR(1000) NOT NULL DEFAULT '',
 tags JSONB NOT NULL DEFAULT '[]'::jsonb,
 workflow JSONB NOT NULL,
 source_recording VARCHAR(255),
 community_workflow_id INTEGER,
 is_public BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT rdp_saved_workflows_size CHECK (pg_column_size(workflow) <= 2097152)
);
CREATE INDEX IF NOT EXISTS idx_rdp_saved_workflows_owner_updated ON public.rdp_saved_workflows (owner_id, updated_at DESC);
ALTER TABLE public.rdp_saved_workflows ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS rdp_saved_workflows_owner_select ON public.rdp_saved_workflows;
CREATE POLICY rdp_saved_workflows_owner_select ON public.rdp_saved_workflows FOR SELECT USING (owner_id = (auth.jwt() ->> 'sub')::integer);
DROP POLICY IF EXISTS rdp_saved_workflows_owner_insert ON public.rdp_saved_workflows;
CREATE POLICY rdp_saved_workflows_owner_insert ON public.rdp_saved_workflows FOR INSERT WITH CHECK (owner_id = (auth.jwt() ->> 'sub')::integer);
DROP POLICY IF EXISTS rdp_saved_workflows_owner_update ON public.rdp_saved_workflows;
CREATE POLICY rdp_saved_workflows_owner_update ON public.rdp_saved_workflows FOR UPDATE USING (owner_id = (auth.jwt() ->> 'sub')::integer) WITH CHECK (owner_id = (auth.jwt() ->> 'sub')::integer);
DROP POLICY IF EXISTS rdp_saved_workflows_owner_delete ON public.rdp_saved_workflows;
CREATE POLICY rdp_saved_workflows_owner_delete ON public.rdp_saved_workflows FOR DELETE USING (owner_id = (auth.jwt() ->> 'sub')::integer);
