-- Community table stores only workflows after explicit user opt-in.
CREATE TABLE IF NOT EXISTS public.rdp_community_workflows (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_id INTEGER NOT NULL REFERENCES public.rdp_users(id) ON DELETE CASCADE,
 name VARCHAR(120) NOT NULL,
 description VARCHAR(1000) NOT NULL DEFAULT '',
 tags JSONB NOT NULL DEFAULT '[]'::jsonb,
 workflow JSONB NOT NULL,
 is_public BOOLEAN NOT NULL DEFAULT TRUE CHECK (is_public = TRUE),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CONSTRAINT rdp_community_workflows_size CHECK (pg_column_size(workflow) <= 2097152)
);
CREATE INDEX IF NOT EXISTS idx_rdp_community_workflows_created ON public.rdp_community_workflows (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_rdp_community_workflows_owner ON public.rdp_community_workflows (owner_id);
ALTER TABLE public.rdp_community_workflows ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS rdp_community_workflows_public_read ON public.rdp_community_workflows;
CREATE POLICY rdp_community_workflows_public_read ON public.rdp_community_workflows FOR SELECT USING (is_public = TRUE);
